CREATE TABLE orders (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id               BIGINT       NOT NULL REFERENCES books (id),
    buyer_id              BIGINT       NOT NULL REFERENCES users (id),
    seller_id             BIGINT       NOT NULL REFERENCES users (id),
    delivery_method       VARCHAR(10)  NOT NULL,
    status                VARCHAR(20)  NOT NULL,
    book_price            INT          NOT NULL,
    credits_used          INT          NOT NULL,
    shipping_fee          INT          NOT NULL,
    platform_fee          INT          NOT NULL,
    cash_paid             INT          NOT NULL,
    payment_mode          VARCHAR(10)  NOT NULL,
    seller_payout         VARCHAR(10)  NOT NULL,
    seller_payout_amount  INT          NOT NULL,
    handover_code         VARCHAR(4),
    ship_name             VARCHAR(80),
    ship_phone            VARCHAR(13),
    ship_address          VARCHAR(300),
    ship_city             VARCHAR(60),
    ship_pincode          VARCHAR(6),
    tracking_note         VARCHAR(200),
    cancel_reason         VARCHAR(200),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at          TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_orders_buyer ON orders (buyer_id, created_at);
CREATE INDEX idx_orders_seller ON orders (seller_id, created_at);
CREATE INDEX idx_orders_book ON orders (book_id);

-- Every change to a user's credits is one row; the balance is the sum.
CREATE TABLE credit_entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    amount      INT          NOT NULL,
    kind        VARCHAR(20)  NOT NULL,
    order_id    BIGINT       REFERENCES orders (id),
    note        VARCHAR(120) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_credit_entries_user ON credit_entries (user_id, created_at);
