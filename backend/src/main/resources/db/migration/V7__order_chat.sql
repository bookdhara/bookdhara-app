-- Buyer and seller chat inside an order, so nobody has to share a phone number.
CREATE TABLE order_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    sender_id   BIGINT        NOT NULL REFERENCES users (id),
    body        VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_order_messages_order ON order_messages (order_id, id);
CREATE INDEX idx_order_messages_sender ON order_messages (sender_id, created_at);

-- Last message each side has seen (for unread counts), and when we last emailed them about chat.
ALTER TABLE orders ADD COLUMN buyer_read_upto BIGINT NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN seller_read_upto BIGINT NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN buyer_chat_emailed_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE orders ADD COLUMN seller_chat_emailed_at TIMESTAMP WITH TIME ZONE;
