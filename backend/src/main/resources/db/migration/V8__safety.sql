-- Deleted accounts keep their row (orders on the other side still need it) but lose personal data.
ALTER TABLE users ADD COLUMN deleted_at TIMESTAMP WITH TIME ZONE;

-- "I don't want to deal with this person": hides their listings and stops buying and chat both ways.
CREATE TABLE user_blocks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id  BIGINT NOT NULL REFERENCES users (id),
    blocked_id  BIGINT NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_user_blocks UNIQUE (blocker_id, blocked_id)
);
CREATE INDEX idx_user_blocks_blocked ON user_blocks (blocked_id);

-- Reports of a listing or a person, reviewed by the BookDhara team.
CREATE TABLE reports (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id  BIGINT       NOT NULL REFERENCES users (id),
    target_type  VARCHAR(10)  NOT NULL,
    target_id    BIGINT       NOT NULL,
    reason       VARCHAR(30)  NOT NULL,
    details      VARCHAR(500),
    status       VARCHAR(10)  NOT NULL DEFAULT 'OPEN',
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_reports_once UNIQUE (reporter_id, target_type, target_id)
);
CREATE INDEX idx_reports_status ON reports (status, created_at);
