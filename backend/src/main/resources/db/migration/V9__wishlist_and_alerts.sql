-- Books a person saved for later.
CREATE TABLE wishlist_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    book_id     BIGINT NOT NULL REFERENCES books (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_wishlist UNIQUE (user_id, book_id)
);

-- "Tell me when this book is listed": matched against new listings' title, author and ISBN.
CREATE TABLE book_alerts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL REFERENCES users (id),
    query             VARCHAR(120) NOT NULL,
    query_lower       VARCHAR(120) NOT NULL,
    city              VARCHAR(60),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    last_notified_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ux_book_alerts UNIQUE (user_id, query_lower)
);
