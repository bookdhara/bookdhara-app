CREATE TABLE books (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id         BIGINT       NOT NULL REFERENCES users (id),
    isbn              VARCHAR(13),
    title             VARCHAR(200) NOT NULL,
    author            VARCHAR(200),
    mrp               INT,
    price             INT          NOT NULL,
    book_condition    VARCHAR(20)  NOT NULL,
    note              VARCHAR(500),
    city              VARCHAR(60)  NOT NULL,
    pincode           VARCHAR(6)   NOT NULL,
    allows_pickup     BOOLEAN      NOT NULL,
    allows_shipping   BOOLEAN      NOT NULL,
    payout            VARCHAR(10)  NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_books_status_created ON books (status, created_at);
CREATE INDEX idx_books_seller ON books (seller_id);
CREATE INDEX idx_books_city ON books (city);

-- Photos are kept in the database for now (small, resized on the phone).
-- Move to object storage once there are many listings.
CREATE TABLE book_photos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id       BIGINT       NOT NULL REFERENCES books (id),
    position      INT          NOT NULL,
    content_type  VARCHAR(30)  NOT NULL,
    data          BYTEA        NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_book_photos_book ON book_photos (book_id, position);
